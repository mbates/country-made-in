/**
 * Regenerates src/shared/origin/countries.data.ts.
 *
 *   npm run generate:countries
 *
 * Names come from the Node ICU database (`Intl.DisplayNames`), the codes from the
 * official ISO 3166-1 alpha-2 list below. ICU alone is not usable as the source of
 * codes: it also resolves deprecated assignments (BU, TP, ZR) and CLDR pseudo-regions
 * (XA, XB), which would put duplicate and nonsense entries in the table.
 *
 * This runs offline and at author time only. Country data is bundled, never fetched.
 */
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

// ISO 3166-1 alpha-2, officially assigned. 249 entries.
const CODES = `
AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ
BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ
CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ
DE DJ DK DM DO DZ
EC EE EG EH ER ES ET
FI FJ FK FM FO FR
GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY
HK HM HN HR HT HU
ID IE IL IM IN IO IQ IR IS IT
JE JM JO JP
KE KG KH KI KM KN KP KR KW KY KZ
LA LB LC LI LK LR LS LT LU LV LY
MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ
NA NC NE NF NG NI NL NO NP NR NU NZ
OM
PA PE PF PG PH PK PL PM PN PR PS PT PW PY
QA
RE RO RS RU RW
SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ
TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ
UA UG UM US UY UZ
VA VC VE VG VI VN VU
WF WS
YE YT
ZA ZM ZW
`
  .trim()
  .split(/\s+/)

const display = new Intl.DisplayNames(['en'], { type: 'region' })

/** Regional indicator symbols: 'GB' -> 🇬🇧. Derived, so no flag assets to ship. */
const flag = (code) => String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65))

const rows = CODES.map((code) => {
  const name = display.of(code)
  if (!name || name === code) throw new Error(`ICU has no name for ${code}`)
  return { code, name, flag: flag(code) }
})

const seen = new Map()
for (const { code, name } of rows) {
  if (seen.has(name)) throw new Error(`Duplicate name ${name}: ${seen.get(name)} and ${code}`)
  seen.set(name, code)
}

// Match Prettier's `singleQuote` rule so a regenerated file is already formatted:
// single quotes, unless the name itself contains one (Côte d'Ivoire).
const quote = (s) => (s.includes("'") ? JSON.stringify(s) : `'${s}'`)

const body = rows
  .map((r) => `  { code: '${r.code}', name: ${quote(r.name)}, flag: '${r.flag}' },`)
  .join('\n')

const file = `// Generated by scripts/generate-countries.mjs — do not edit by hand.
// Names from the Node ICU database; codes are ISO 3166-1 alpha-2.
// Regenerate with: npm run generate:countries

import type { Country } from './types'

export const COUNTRIES: readonly Country[] = [
${body}
]
`

const out = resolve(import.meta.dirname, '../src/shared/origin/countries.data.ts')
writeFileSync(out, file)
console.log(`Wrote ${rows.length} countries to ${out}`)
